-- Sistema de gestion para revendedores
-- Ejecutar en Oracle SQL Workshop > SQL Scripts o en SQL Developer.
-- Requiere Oracle Database 12c o superior (columnas IDENTITY).

CREATE TABLE roles (
    id_rol NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR2(30) NOT NULL UNIQUE,
    descripcion VARCHAR2(200),
    CONSTRAINT ck_roles_nombre CHECK (nombre IN ('ADMINISTRADOR', 'VENDEDOR'))
);

CREATE TABLE usuarios (
    id_usuario NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_rol NUMBER NOT NULL,
    nombre VARCHAR2(100) NOT NULL,
    correo VARCHAR2(150) NOT NULL UNIQUE,
    hash_contrasena VARCHAR2(255) NOT NULL,
    activo NUMBER(1) DEFAULT 1 NOT NULL,
    creado_en TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_usuarios_roles FOREIGN KEY (id_rol) REFERENCES roles(id_rol),
    CONSTRAINT ck_usuarios_activo CHECK (activo IN (0, 1))
);

CREATE TABLE proveedores (
    id_proveedor NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR2(120) NOT NULL,
    contacto VARCHAR2(100),
    telefono VARCHAR2(30),
    correo VARCHAR2(150),
    direccion VARCHAR2(250),
    activo NUMBER(1) DEFAULT 1 NOT NULL,
    creado_en TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT ck_proveedores_activo CHECK (activo IN (0, 1))
);

CREATE TABLE productos (
    id_producto NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_proveedor NUMBER NOT NULL,
    nombre VARCHAR2(150) NOT NULL,
    descripcion VARCHAR2(500),
    precio_compra NUMBER(12,2) NOT NULL,
    margen_porcentaje NUMBER(7,2) DEFAULT 0 NOT NULL,
    precio_venta NUMBER(12,2) NOT NULL,
    existencia NUMBER(10) DEFAULT 0 NOT NULL,
    activo NUMBER(1) DEFAULT 1 NOT NULL,
    creado_en TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_productos_proveedores FOREIGN KEY (id_proveedor) REFERENCES proveedores(id_proveedor),
    CONSTRAINT ck_productos_compra CHECK (precio_compra >= 0),
    CONSTRAINT ck_productos_margen CHECK (margen_porcentaje >= 0),
    CONSTRAINT ck_productos_venta CHECK (precio_venta >= 0),
    CONSTRAINT ck_productos_existencia CHECK (existencia >= 0),
    CONSTRAINT ck_productos_activo CHECK (activo IN (0, 1))
);

CREATE TABLE clientes (
    id_cliente NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR2(120) NOT NULL,
    telefono VARCHAR2(30),
    correo VARCHAR2(150),
    direccion VARCHAR2(250),
    creado_en TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE pedidos (
    id_pedido NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente NUMBER NOT NULL,
    id_usuario NUMBER NOT NULL,
    fecha_pedido TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    estado VARCHAR2(20) DEFAULT 'PENDIENTE' NOT NULL,
    observaciones VARCHAR2(500),
    CONSTRAINT fk_pedidos_clientes FOREIGN KEY (id_cliente) REFERENCES clientes(id_cliente),
    CONSTRAINT fk_pedidos_usuarios FOREIGN KEY (id_usuario) REFERENCES usuarios(id_usuario),
    CONSTRAINT ck_pedidos_estado CHECK (estado IN ('PENDIENTE', 'CONFIRMADO', 'ENVIADO', 'ENTREGADO', 'CANCELADO'))
);

CREATE TABLE detalle_pedido (
    id_detalle NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pedido NUMBER NOT NULL,
    id_producto NUMBER NOT NULL,
    cantidad NUMBER(10) NOT NULL,
    precio_unitario NUMBER(12,2) NOT NULL,
    CONSTRAINT fk_detalle_pedidos FOREIGN KEY (id_pedido) REFERENCES pedidos(id_pedido) ON DELETE CASCADE,
    CONSTRAINT fk_detalle_productos FOREIGN KEY (id_producto) REFERENCES productos(id_producto),
    CONSTRAINT uq_detalle_pedido_producto UNIQUE (id_pedido, id_producto),
    CONSTRAINT ck_detalle_cantidad CHECK (cantidad > 0),
    CONSTRAINT ck_detalle_precio CHECK (precio_unitario >= 0)
);

CREATE TABLE pagos (
    id_pago NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pedido NUMBER NOT NULL,
    monto NUMBER(12,2) NOT NULL,
    metodo VARCHAR2(25) NOT NULL,
    fecha_pago TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    referencia VARCHAR2(100),
    estado VARCHAR2(20) DEFAULT 'REGISTRADO' NOT NULL,
    CONSTRAINT fk_pagos_pedidos FOREIGN KEY (id_pedido) REFERENCES pedidos(id_pedido),
    CONSTRAINT ck_pagos_monto CHECK (monto > 0),
    CONSTRAINT ck_pagos_metodo CHECK (metodo IN ('EFECTIVO', 'TRANSFERENCIA', 'TARJETA', 'OTRO')),
    CONSTRAINT ck_pagos_estado CHECK (estado IN ('REGISTRADO', 'ANULADO'))
);

CREATE INDEX ix_productos_proveedor ON productos(id_proveedor);
CREATE INDEX ix_pedidos_cliente ON pedidos(id_cliente);
CREATE INDEX ix_pedidos_usuario ON pedidos(id_usuario);
CREATE INDEX ix_pedidos_fecha_estado ON pedidos(fecha_pedido, estado);
CREATE INDEX ix_detalle_producto ON detalle_pedido(id_producto);
CREATE INDEX ix_pagos_pedido ON pagos(id_pedido);
